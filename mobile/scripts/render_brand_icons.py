"""Render the brand mark into the Android launcher assets.

The vector itself comes from assets/brand-vector.json, which is generated by
scripts/extract_brand_vector.py from the Figma reference. Keeping one source
of truth means the launcher icons and the in-app mark can never drift apart.

Outputs (all under mobile/assets):
  brand-icon.png         1024x1024, mark at 960, on #F8FBFF
  brand-adaptive.png     1024x1024, mark at 660, transparent
  brand-monochrome.png   1024x1024, mark at 660, transparent, strokes only

Usage:  python scripts/render_brand_icons.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
VECTOR = ASSETS / "brand-vector.json"

CANVAS = 1024
BACKDROP = (248, 251, 255, 255)  # #F8FBFF


# --------------------------------------------------------------- path parsing
TOKEN = re.compile(r"[MCZLz]|-?\d+(?:\.\d+)?")


def parse_path(d: str):
    """Parse the subset of SVG path syntax the generator emits: M, C, L, Z."""
    tokens = TOKEN.findall(d)
    i = 0
    current = (0.0, 0.0)
    start = (0.0, 0.0)
    segments = []          # ("C", x1, y1, x2, y2, x, y) | ("L", x, y)
    moved = False
    while i < len(tokens):
        op = tokens[i]
        i += 1
        if op == "M":
            current = (float(tokens[i]), float(tokens[i + 1]))
            i += 2
            start = current
            moved = True
        elif op == "L":
            current = (float(tokens[i]), float(tokens[i + 1]))
            i += 2
            segments.append(("L", current[0], current[1]))
        elif op == "C":
            pts = [float(v) for v in tokens[i:i + 6]]
            i += 6
            current = (pts[4], pts[5])
            segments.append(("C", *pts))
        elif op in ("Z", "z"):
            segments.append(("L", start[0], start[1]))
            current = start
    return segments, (start if moved else current)


def flatten(segments, steps=24):
    """Turn the parsed path into a polyline."""
    points = []
    cursor = None
    for seg in segments:
        if seg[0] == "L":
            cursor = (seg[1], seg[2])
            points.append(cursor)
        else:
            _, x1, y1, x2, y2, x, y = seg
            p0 = cursor if cursor is not None else (x1, y1)
            for step in range(1, steps + 1):
                t = step / steps
                mt = 1 - t
                bx = (mt ** 3) * p0[0] + 3 * (mt ** 2) * t * x1 + 3 * mt * (t ** 2) * x2 + (t ** 3) * x
                by = (mt ** 3) * p0[1] + 3 * (mt ** 2) * t * y1 + 3 * mt * (t ** 2) * y2 + (t ** 3) * y
                points.append((bx, by))
            cursor = (x, y)
    return points


# ------------------------------------------------------------------- painting
def hex_rgb(value: str):
    value = value.lstrip("#")
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def gradient_disc(size: int, c0, c1) -> Image.Image:
    """A diagonal linear gradient clipped to a circle."""
    try:
        import numpy as np

        xs = np.linspace(0, 1, size, dtype=np.float32)
        ys = np.linspace(0, 1, size, dtype=np.float32)
        t = (xs[None, :] + ys[:, None]) / 2.0
        grad = np.zeros((size, size, 3), dtype=np.float32)
        for k in range(3):
            grad[:, :, k] = c0[k] * (1 - t) + c1[k] * t
        layer = Image.fromarray(grad.astype("uint8"), "RGB").convert("RGBA")
    except ImportError:  # pragma: no cover - numpy is optional
        layer = Image.new("RGBA", (size, size))
        px = layer.load()
        for y in range(size):
            for x in range(size):
                t = (x + y) / (2 * max(1, size - 1))
                px[x, y] = tuple(round(c0[k] * (1 - t) + c1[k] * t) for k in range(3)) + (255,)

    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, size - 1, size - 1), fill=255)
    layer.putalpha(mask)
    return layer


def stroke_polyline(draw, points, width, closed):
    if len(points) < 2:
        return
    draw.line(points, fill="white", width=width, joint="curve")
    radius = width / 2.0
    for x, y in points:
        draw.ellipse((x - radius, y - radius, x + radius, y + radius), fill="white")


def render(vector, diameter: int, monochrome: bool) -> Image.Image:
    grid = vector["grid"]
    scale = diameter / grid
    canvas = Image.new("RGBA", (CANVAS, CANVAS), (0, 0, 0, 0))
    left = (CANVAS - diameter) / 2.0
    top = (CANVAS - diameter) / 2.0

    if not monochrome:
        disc = gradient_disc(
            diameter,
            hex_rgb(vector["gradient"]["from"]),
            hex_rgb(vector["gradient"]["to"]),
        )
        canvas.alpha_composite(disc, (int(left), int(top)))

    layer = Image.new("RGBA", (CANVAS, CANVAS), (0, 0, 0, 0))
    draw = ImageDraw.Draw(layer)

    def place(points):
        return [(left + x * scale, top + y * scale) for x, y in points]

    outline_w = max(1, round(vector["outlineStrokeWidth"] * scale))
    ecg_w = max(1, round(vector["strokeWidth"] * scale))

    outline_segs, outline_start = parse_path(vector["outline"])
    stroke_polyline(
        draw,
        place([outline_start] + flatten(outline_segs)),
        outline_w,
        True,
    )

    centre = vector["centreLine"]
    stroke_polyline(
        draw,
        place([(centre["x"], centre["y0"]), (centre["x"], centre["y1"])]),
        ecg_w,
        False,
    )
    ecg_segs, ecg_start = parse_path(vector["ecg"])
    stroke_polyline(draw, place([ecg_start] + flatten(ecg_segs)), ecg_w, False)

    canvas.alpha_composite(layer)
    return canvas


def main() -> int:
    if not VECTOR.exists():
        print(f"missing {VECTOR}\nrun scripts/extract_brand_vector.py first")
        return 1
    vector = json.loads(VECTOR.read_text(encoding="utf-8"))

    icon = render(vector, 960, monochrome=False)
    if icon.size[0] == CANVAS:
        flat = Image.new("RGBA", (CANVAS, CANVAS), BACKDROP)
        flat.alpha_composite(icon)
        icon = flat
    icon.save(ASSETS / "brand-icon.png")

    render(vector, 660, monochrome=False).save(ASSETS / "brand-adaptive.png")
    render(vector, 660, monochrome=True).save(ASSETS / "brand-monochrome.png")

    print(f"stroke IoU recorded in the vector: {vector.get('iou')}")
    for name in ("brand-icon.png", "brand-adaptive.png", "brand-monochrome.png"):
        path = ASSETS / name
        print(f"  {name}: {path.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
